/** Content migration checks; no database or production credentials required. */
import assert from "node:assert/strict";
import { DEFAULT_PRODUCT_IMAGE, defaultHomepageContent, homepageSchema } from "../src/lib/homepage-schema";
import { hasSuppliedBottleViews, PRODUCT_VIEWS, productDragSteps, wrapProductView } from "../src/lib/product-views";

const defaults = defaultHomepageContent();
assert(homepageSchema.safeParse(defaults).success);
assert.equal(defaults.images.oil.url, DEFAULT_PRODUCT_IMAGE);
const oldBottle = structuredClone(defaults);
oldBottle.images.oil.url = "/chulimaar/product/apricot-kernel-oil.png";
assert.equal(homepageSchema.parse(oldBottle).images.oil.url, DEFAULT_PRODUCT_IMAGE, "Upgrade the bundled image to its transparent cutout.");
const legacy = JSON.parse(JSON.stringify(defaults));
delete legacy.product;
legacy.images.oil.url = "";
legacy.text.oilTitle = "Owner's saved product heading";
const upgraded = homepageSchema.parse(legacy);
assert.equal(upgraded.images.oil.url, DEFAULT_PRODUCT_IMAGE);
assert.equal(upgraded.product.animation, true);
assert.deepEqual(upgraded.text, legacy.text);
assert.deepEqual(upgraded.hero, legacy.hero);
assert.deepEqual(upgraded.faqs, legacy.faqs);
legacy.images.oil.url = "/uploads/chulimaar/existing.webp";
legacy.images.oil.alt = "Owner's existing photograph";
assert.deepEqual(homepageSchema.parse(legacy).images.oil, legacy.images.oil, "Keep an existing owner photo.");
delete legacy.hero;
assert(homepageSchema.safeParse(legacy).success, "Support content from before both interactive features.");
const edited = structuredClone(upgraded);
edited.product.animation = false;
assert.equal(homepageSchema.parse(edited).product.animation, false);
edited.images.oil.url = "";
const roundTrip = homepageSchema.parse(JSON.parse(JSON.stringify(edited)));
assert.equal(roundTrip.images.oil.url, "", "An intentional removal must not resurrect the default bottle.");
assert.equal(roundTrip.product.animation, false);
assert(!homepageSchema.safeParse({ ...edited, product: { animation: "false" } }).success);
assert(!homepageSchema.safeParse({ ...edited, product: null }).success);
edited.images.oil.url = DEFAULT_PRODUCT_IMAGE;
edited.images.oil.alt = "";
assert(!homepageSchema.safeParse(edited).success, "An image still requires its description.");
edited.images.oil.alt = defaults.images.oil.alt;
edited.images.oil.url = "https://untrusted.example/bottle.png";
assert(!homepageSchema.safeParse(edited).success);
assert.equal(PRODUCT_VIEWS.length, 4);
assert.equal(new Set(PRODUCT_VIEWS.map(view => view.src)).size, 4);
assert(hasSuppliedBottleViews(DEFAULT_PRODUCT_IMAGE));
assert(!hasSuppliedBottleViews("/uploads/chulimaar/custom.webp"), "Custom owner photos must not inherit the supplied bottle angles.");
assert(!hasSuppliedBottleViews(""));
assert.equal(wrapProductView(-1), 3);
assert.equal(wrapProductView(4), 0);
assert.equal(wrapProductView(-9), 3);
assert.equal(productDragSteps(49, 250), 0, "Small movements should not rotate.");
assert.equal(productDragSteps(100, 250), 2);
assert.equal(productDragSteps(-100, 250), -2);
assert.equal(productDragSteps(35, 0), 0, "Very small stages still need a deliberate gesture.");
console.log("Passed: four unique product views, custom-photo isolation, circular rotation and deliberate drag thresholds.");
console.log("Passed: product defaults, old-content migration, existing-photo/text preservation, dual-feature migration, animation setting, intentional removal persistence, required alt and image URL validation.");
